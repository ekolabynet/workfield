#
# 2. NADPISYWANIE ZAMIAST SCALANIA. Tamta funkcja pisze caly plik od nowa -
#    kto dolozyl sobie kafel recznie, traci go. Ten modul scala: obce klucze,
#    kolejnosc i reczne kafle zostaja, a stary plik dostaje kopie.
#
# 3. KAFEL PO WARSTWIE, NIE PO ETYKIECIE. Projekty dendro maja kafel
#    tyczenia pod "T" od 20.09. Sprawdzanie po etykiecie dolozyloby drugi
#    kafel na te sama warstwe.
#
