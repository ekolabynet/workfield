        continue
    kroki = stary.get('kroki') or [{}]
    if kroki[0].get('typ') == KROK_MODULU[mid] and stary.get('wersja') == nowy['wersja']:
        juzZrobione.append('%s juz na wersji %d' % (sciezka, nowy['wersja']))
        continue
    # SCALAMY kluczami, nie podmieniamy calosci - ewentualne wlasne pola
    # w repo maja przezyc.
    scalony = dict(stary)
    scalony.update(nowy)
    opisyDoZmiany[sciezka] = scalony

