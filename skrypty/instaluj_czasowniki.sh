                if wpis.get('wersja') != OPISY[wpis['id']]['wersja']:
                    wpis['wersja'] = OPISY[wpis['id']]['wersja']
                    zmiana = True
        brak = set(OPISY) - znalezione
        if brak:
            bledy.append('%s nie wymienia modulow: %s' % (KATALOG, ', '.join(sorted(brak))))
        elif zmiana:
            katalogDoZmiany = kat
        else:
            juzZrobione.append('%s juz ma wersje 2' % KATALOG)

