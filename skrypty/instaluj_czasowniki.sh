# --------------------------------------------------------------------
#   proba4, 11 sekcji, 45 sprawdzen:
#     - tabela w pliku, trzy pola, geometria punktowa, uklad z projektu;
#     - PROJEKT WCZYTANY OD NOWA Z DYSKU widzi warstwe i jej pola;
#     - drugie uruchomienie: zero nowych warstw, zero nowych kafli;
#     - stara etykieta "T" nietknieta;
#     - "Punkty" i "Poligony" dostaja ROZNE etykiety;
#     - obcy klucz _uwaga i reczny kafel przezywaja scalanie, stary plik
#       ma kopie obok;
#     - zepsuty JSON NIE jest nadpisywany, a komunikat mowi o tym wprost;
#     - kafel na nieistniejaca warstwe = odmowa z nazwa warstwy;
#     - tabela z punktem "z terenu" zostaje WCZYTANA, nie nadpisana.
#   proba3, 11 sekcji: kazda odmowa nadal mowi dlaczego; modul nieodwracalny
#     zostawia OBIE kopie (projekt i baze); flagi pyta/powtarzalny w QML.
#   proba i proba2: zalaczniki N:1 bez zmian.
#
