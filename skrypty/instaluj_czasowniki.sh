    try:
        kat = json.loads(czytaj(KATALOG))
    except ValueError as e:
        kat = None
        bledy.append('%s nie jest poprawnym JSON-em: %s' % (KATALOG, e))
    if kat is not None:
        zmiana = False
        znalezione = set()
        for wpis in kat.get('moduly', []):
            if wpis.get('id') in OPISY:
