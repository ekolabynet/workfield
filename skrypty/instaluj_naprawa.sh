# ----------
#   src/core/wyposazenie.{h,cpp}          dwa czasowniki ustawien: przyciaganie
#                                         i edycja topologiczna. Obie zmiany
#                                         ODWRACALNE, obie z kopia projektu,
#                                         BEZ stempla (to nie sa moduly).
#   src/core/utils/narzedziaprojektu.cpp  pola `czasownik` i `parametr`
