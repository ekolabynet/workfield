def czytaj(p):
    return open(p, encoding='utf-8').read()

def rozpakuj(b):
    return zlib.decompress(base64.b64decode(''.join(b.split())))

bledy, juzZrobione, doZapisu = [], [], []

for cel, (przed, po, _b) in CALE.items():
    if not os.path.exists(cel):
        bledy.append('brak pliku %s' % cel)
        continue
    suma = hashlib.md5(open(cel, 'rb').read()).hexdigest()
    if suma == po:
        juzZrobione.append('%s juz podmieniony' % cel)
        continue
    if suma not in przed:
        bledy.append('%s ma sume %s, a latka oczekuje jednej z: %s.\n'
                     '       NIE nadpisuje. Przyslij go PELNA SCIEZKA.'
                     % (cel, suma, ', '.join(przed)))
        continue
    doZapisu.append(cel)

zamiany = {}
for plik, kotwica, nowe, opis in ((H, KOTWICA_H, NOWE_H, 'qfappinterface.h: zoomToFeature'),
                                  (C, KOTWICA_C, CIALO + KOTWICA_C, 'qfappinterface.cpp: zoomToFeature')):
    if not os.path.exists(plik):
        bledy.append('brak pliku %s' % plik)
        continue
    t = czytaj(plik)
    if 'zoomToFeature' in t:
        juzZrobione.append(opis)
        continue
    if t.count(kotwica) != 1:
        bledy.append('%s: kotwica „zoomToLayer" wystepuje %d x (oczekiwano 1)'
                     % (plik, t.count(kotwica)))
        continue
    zamiany[plik] = t.replace(kotwica, nowe, 1)

if bledy:
    print('NIC NIE ZAPISANO. Zarzuty:')
    for b in bledy:
        print(' -', b)
    sys.exit(1)

for opis in juzZrobione:
    print('  juz zrobione:', opis)

zmienione = 0
for cel in doZapisu:
    open(cel, 'wb').write(rozpakuj(CALE[cel][2]))
    print('  %-46s %s' % (cel, 'PODMIENIONY'))
    zmienione += 1
for plik, tresc in zamiany.items():
    open(plik, 'w', encoding='utf-8').write(tresc)
    print('  %-46s %s' % (plik, 'zoomToFeature dolozone'))
    zmienione += 1

print()
print('  zmienionych plikow: %d' % zmienione)
