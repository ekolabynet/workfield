#        BLEDY W DANYCH · 1
#           obiekt o obwiedni 0.09 m (Rysunek CAD - poligony / fid 2253)...
#        USTAWIENIA · 2
#           Kafle paska szybkiego przechwytu, Zalaczniki N:1
#        [ BLEDY ]  [ USTAWIENIA ]
#
#    Odsylacze na JASNOZIELONYM TLE (#C8E6C9), nie samym kolorem liter:
#    na ciemnym dymku link rozniacy sie wylacznie barwa tekstu ginie
