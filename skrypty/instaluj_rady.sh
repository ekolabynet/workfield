    '  function displayToastTrwaly(message, type, action_text, action_function) {\n'
    '    toast.pokazTrwaly(message, type, action_text, action_function);\n'
    '  }\n')

NOWA_TRWALA = (
    '\n'
    '  //! Dymek, ktory NIE GASNIE SAM — czeka na tapniecie, ma naglowek\n'
    '  //! i wlasne odsylacze. Uzywa go dymek startowy: wymienia po nazwie\n'
    '  //! kilka rzeczy naraz, prowadzi do DWOCH roznych okien i leci RAZ.\n'
