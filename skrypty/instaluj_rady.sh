    '  //!\n'
    '  //! `akcje` to lista map { etykieta, akcja } — zero, jeden albo dwa\n'
    '  //! odsylacze, kazdy na jasnozielonym tle.\n'
    '  function displayToastTrwaly(naglowek, message, type, akcje) {\n'
    '    toast.pokazTrwaly(naglowek, message, type, akcje);\n'
    '  }\n')


def czytaj(p):
    return open(p, encoding='utf-8').read()


def rozpakuj(b):
    return zlib.decompress(base64.b64decode(''.join(b.split())))


bledy = []

# --- pliki podmieniane w calosci ---------------------------------------
caleDoZapisu = []
juzZrobione = []
for cel, (przed, po, _b) in CALE.items():
    if not os.path.exists(cel):
        bledy.append('brak pliku %s' % cel)
        continue
    suma = hashlib.md5(open(cel, 'rb').read()).hexdigest()
    if suma == po:
        juzZrobione.append('%s juz podmieniony' % cel)
        continue
    if suma not in przed:
        bledy.append(
            '%s ma sume %s, a latka oczekuje jednej z: %s.\n'
            '       Ten plik zostal w miedzyczasie zmieniony. NIE nadpisuje go.\n'
            '       Przyslij go PELNA SCIEZKA, zlozymy latke na tym, co jest.'
            % (cel, suma, ', '.join(przed)))
        continue
    caleDoZapisu.append(cel)

# --- QgisMobileapp: trzy mozliwe stany, jeden wynik --------------------
#
# Zwykla zamiana z jedna kotwica tu nie wystarcza: po `instaluj_dymek2.sh`
# w pliku jest STARA wersja funkcji, a kotwica pierwotna NADAL TAM JEST
# (tamta latka dopisala za nia). Slepe dopisanie zrobiloby wiec DRUGA
# definicje `displayToastTrwaly` — czyli kod, ktory by sie nie skompilowal.
appDoZapisu = None
if not os.path.exists(APP):
    bledy.append('brak pliku %s' % APP)
else:
    tApp = czytaj(APP)
    if tApp.count(NOWA_TRWALA) >= 1:
        juzZrobione.append('%s: displayToastTrwaly juz z naglowkiem' % APP)
    elif tApp.count(STARA_TRWALA) == 1:
        appDoZapisu = tApp.replace(STARA_TRWALA, NOWA_TRWALA, 1)
    elif tApp.count(KOTWICA) == 1:
        appDoZapisu = tApp.replace(KOTWICA, KOTWICA + NOWA_TRWALA, 1)
    else:
        bledy.append(
            '%s: nie poznaje stanu pliku — ani nowej funkcji, ani starej,\n'
            '       ani kotwicy `displayToast` (wystapien: %d).\n'
            '       Przyslij /DATA/SOFT/GIS/QFIELD_Pro/QField/%s'
            % (APP, tApp.count(KOTWICA), APP))

if bledy:
    print('NIC NIE ZAPISANO. Zarzuty:')
    for b in bledy:
        print(' -', b)
    sys.exit(1)

for opis in juzZrobione:
    print('  juz zrobione:', opis)

# --- ZAPIS -------------------------------------------------------------
zmienione = 0
for cel in caleDoZapisu:
    open(cel, 'wb').write(rozpakuj(CALE[cel][2]))
    print('  %-42s %s' % (cel, 'PODMIENIONY W CALOSCI'))
    zmienione += 1

if appDoZapisu is not None:
    open(APP, 'w', encoding='utf-8').write(appDoZapisu)
    print('  %-42s %s' % (APP, 'displayToastTrwaly z naglowkiem'))
    zmienione += 1

print()
print('  zmienionych plikow: %d' % zmienione)
