STARA_TRWALA = (
    '\n'
    '  //! Dymek, ktory NIE GASNIE SAM — czeka na tapniecie. Uzywa go dymek\n'
    '  //! startowy „Temu projektowi brakuje…”, bo wymienia po nazwie kilka\n'
