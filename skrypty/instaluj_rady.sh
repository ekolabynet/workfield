#
#        opis:  przyciaganie lapie segment, a najmniejszy obiekt ma 0.1 m
#        rada:  Zejdz z tolerancja przyciagania do najwyzej 0.05 m -
#               polowy najmniejszego obiektu - albo zostaw przyciaganie
#               tylko do WIERZCHOLKA, bez odcinka.
#
#    Rada jest LICZONA, nie ogolna: prog bierze sie z rozmiaru obiektu
#    w tym projekcie, nazwa warstwy z tej warstwy, a przy braku slownika
#    rada wskazuje dokladna droge („Wyposazenie -> Slownik gatunkow ->
#    Pobierz z sieci"), bo ta droga od dzis istnieje.
#
#    Rada wyswietla sie w SZUFLADZIE pod ostrzezeniem i w oknie „Jak ten
#    projekt jest ustawiony" pod kazdym wpisem.
#
# CO WCHODZI
# ----------
#   src/core/utils/narzedziaprojektu.cpp  pole `rada` przy kazdym z siedmiu
#   src/app/qml/QfMainDrawer.qml          rada pod ostrzezeniem
#   src/app/qml/QfNaprawaProjektu.qml     rada pod kazdym wpisem
#   src/app/qml/QfKontrolaProjektu.qml    tresc dymka: naglowek + sekcje
#   src/app/qml/QgisMobileapp.qml         displayToastTrwaly z naglowkiem
